/* =========================================================
   0. BORRADO DE OBJETOS
   ========================================================= */

DROP TABLE pago CASCADE CONSTRAINTS PURGE;
DROP TABLE dosis CASCADE CONSTRAINTS PURGE;
DROP TABLE receta CASCADE CONSTRAINTS PURGE;
DROP TABLE medicamento CASCADE CONSTRAINTS PURGE;
DROP TABLE paciente CASCADE CONSTRAINTS PURGE;
DROP TABLE medico CASCADE CONSTRAINTS PURGE;
DROP TABLE digitador CASCADE CONSTRAINTS PURGE;
DROP TABLE diagnostico CASCADE CONSTRAINTS PURGE;
DROP TABLE banco CASCADE CONSTRAINTS PURGE;
DROP TABLE tipo_receta CASCADE CONSTRAINTS PURGE;
DROP TABLE especialidad CASCADE CONSTRAINTS PURGE;
DROP TABLE comuna CASCADE CONSTRAINTS PURGE;
DROP TABLE ciudad CASCADE CONSTRAINTS PURGE;
DROP TABLE region CASCADE CONSTRAINTS PURGE;

/* =========================================================
   CASO 1 - CREACIÓN DE TABLAS
   ========================================================= */

/* Catálogo geográfico */
CREATE TABLE region (
    id_region NUMBER(5) NOT NULL,
    nombre VARCHAR2(25) NOT NULL
);

ALTER TABLE region
    ADD CONSTRAINT region_pk PRIMARY KEY (id_region);

CREATE TABLE ciudad (
    id_ciudad NUMBER(5) NOT NULL,
    nombre VARCHAR2(25) NOT NULL,
    id_region NUMBER(5) NOT NULL
);

ALTER TABLE ciudad
    ADD CONSTRAINT ciudad_pk PRIMARY KEY (id_ciudad);

ALTER TABLE ciudad
    ADD CONSTRAINT ciudad_region_fk
    FOREIGN KEY (id_region) REFERENCES region(id_region);

/* El identificador de comuna comienza en 1101 y aumenta de 1 en 1 */
CREATE TABLE comuna (
    id_comuna NUMBER(5)
        GENERATED BY DEFAULT AS IDENTITY
        (START WITH 1101 INCREMENT BY 1)
        NOT NULL,
    nombre VARCHAR2(25) NOT NULL,
    id_ciudad NUMBER(5) NOT NULL
);

ALTER TABLE comuna
    ADD CONSTRAINT comuna_pk PRIMARY KEY (id_comuna);

ALTER TABLE comuna
    ADD CONSTRAINT comuna_ciudad_fk
    FOREIGN KEY (id_ciudad) REFERENCES ciudad(id_ciudad);

/* Especialidades médicas */
CREATE TABLE especialidad (
    id_especialidad NUMBER(5)
        GENERATED BY DEFAULT AS IDENTITY
        (START WITH 1 INCREMENT BY 1)
        NOT NULL,
    nombre VARCHAR2(25) NOT NULL
);

ALTER TABLE especialidad
    ADD CONSTRAINT especialidad_pk PRIMARY KEY (id_especialidad);

/* Tipos de receta */
CREATE TABLE tipo_receta (
    id_tipo_receta NUMBER(3) NOT NULL,
    nombre VARCHAR2(25) NOT NULL
);

ALTER TABLE tipo_receta
    ADD CONSTRAINT tipo_receta_pk PRIMARY KEY (id_tipo_receta);

ALTER TABLE tipo_receta
    ADD CONSTRAINT tipo_receta_nombre_uk UNIQUE (nombre);

/* Bancos */
CREATE TABLE banco (
    cod_banco NUMBER(2) NOT NULL,
    nombre VARCHAR2(25) NOT NULL
);

ALTER TABLE banco
    ADD CONSTRAINT banco_pk PRIMARY KEY (cod_banco);

/* Diagnósticos */
CREATE TABLE diagnostico (
    cod_diagnostico NUMBER(3) NOT NULL,
    nombre VARCHAR2(25) NOT NULL
);

ALTER TABLE diagnostico
    ADD CONSTRAINT diagnostico_pk PRIMARY KEY (cod_diagnostico);

/* Medicamentos */
CREATE TABLE medicamento (
    cod_medicamento NUMBER(7) NOT NULL,
    nombre VARCHAR2(25) NOT NULL,
    tipo_medicamento NUMBER(3) NOT NULL,
    via_administra NUMBER(3) NOT NULL
);

ALTER TABLE medicamento
    ADD CONSTRAINT medicamento_pk PRIMARY KEY (cod_medicamento);

/* Pacientes */
CREATE TABLE paciente (
    rut_pac VARCHAR2(25) NOT NULL,
    dv_pac CHAR(1) NOT NULL,
    pnombre VARCHAR2(25) NOT NULL,
    snombre VARCHAR2(25),
    edad DATE NOT NULL,
    telefono NUMBER(11) NOT NULL,
    calle VARCHAR2(25) NOT NULL,
    numeracion NUMBER(5) NOT NULL,
    comuna NUMBER(5) NOT NULL,
    ciudad NUMBER(5) NOT NULL,
    region NUMBER(5) NOT NULL
);

ALTER TABLE paciente
    ADD CONSTRAINT paciente_pk PRIMARY KEY (rut_pac);

ALTER TABLE paciente
    ADD CONSTRAINT paciente_dv_ck
    CHECK (REGEXP_LIKE(dv_pac, '^[0-9K]$'));

ALTER TABLE paciente
    ADD CONSTRAINT paciente_comuna_fk
    FOREIGN KEY (comuna) REFERENCES comuna(id_comuna);

ALTER TABLE paciente
    ADD CONSTRAINT paciente_ciudad_fk
    FOREIGN KEY (ciudad) REFERENCES ciudad(id_ciudad);

ALTER TABLE paciente
    ADD CONSTRAINT paciente_region_fk
    FOREIGN KEY (region) REFERENCES region(id_region);

/* Médicos */
CREATE TABLE medico (
    rut_med NUMBER(8) NOT NULL,
    dv_med CHAR(1) NOT NULL,
    pnombre VARCHAR2(25) NOT NULL,
    snombre VARCHAR2(25),
    papellido VARCHAR2(25) NOT NULL,
    sapellido VARCHAR2(25),
    especialidad NUMBER(5) NOT NULL,
    telefono NUMBER(11) NOT NULL
);

ALTER TABLE medico
    ADD CONSTRAINT medico_pk PRIMARY KEY (rut_med);

ALTER TABLE medico
    ADD CONSTRAINT medico_dv_ck
    CHECK (REGEXP_LIKE(dv_med, '^[0-9K]$'));

ALTER TABLE medico
    ADD CONSTRAINT medico_telefono_uk UNIQUE (telefono);

ALTER TABLE medico
    ADD CONSTRAINT medico_especialidad_fk
    FOREIGN KEY (especialidad) REFERENCES especialidad(id_especialidad);

/* Digitadores */
CREATE TABLE digitador (
    id_digitador NUMBER(20) NOT NULL,
    dv_digitador CHAR(1) NOT NULL,
    pnombre VARCHAR2(25) NOT NULL,
    papellido VARCHAR2(25) NOT NULL
);

ALTER TABLE digitador
    ADD CONSTRAINT digitador_pk PRIMARY KEY (id_digitador);

ALTER TABLE digitador
    ADD CONSTRAINT digitador_dv_ck
    CHECK (REGEXP_LIKE(dv_digitador, '^[0-9K]$'));

/* Recetas */
CREATE TABLE receta (
    cod_receta NUMBER(7) NOT NULL,
    observaciones VARCHAR2(500) NOT NULL,
    fecha_emision DATE NOT NULL,
    fecha_vencimiento VARCHAR2(25),
    id_digitador NUMBER(20) NOT NULL,
    id_pac_rut VARCHAR2(25) NOT NULL,
    id_diagnostico NUMBER(3) NOT NULL,
    med_rut NUMBER(8) NOT NULL,
    id_tipo_receta NUMBER(3) NOT NULL
);

ALTER TABLE receta
    ADD CONSTRAINT receta_pk PRIMARY KEY (cod_receta);

ALTER TABLE receta
    ADD CONSTRAINT receta_digitador_fk
    FOREIGN KEY (id_digitador) REFERENCES digitador(id_digitador);

ALTER TABLE receta
    ADD CONSTRAINT receta_paciente_fk
    FOREIGN KEY (id_pac_rut) REFERENCES paciente(rut_pac);

ALTER TABLE receta
    ADD CONSTRAINT receta_diagnostico_fk
    FOREIGN KEY (id_diagnostico) REFERENCES diagnostico(cod_diagnostico);

ALTER TABLE receta
    ADD CONSTRAINT receta_medico_fk
    FOREIGN KEY (med_rut) REFERENCES medico(rut_med);

ALTER TABLE receta
    ADD CONSTRAINT receta_tipo_fk
    FOREIGN KEY (id_tipo_receta) REFERENCES tipo_receta(id_tipo_receta);

/* Dosis: relación N:M entre receta y medicamento */
CREATE TABLE dosis (
    id_medicamento NUMBER(7) NOT NULL,
    id_receta NUMBER(7) NOT NULL,
    descripcion_dosis VARCHAR2(25) NOT NULL
);

ALTER TABLE dosis
    ADD CONSTRAINT dosis_pk PRIMARY KEY (id_medicamento, id_receta);

ALTER TABLE dosis
    ADD CONSTRAINT dosis_medicamento_fk
    FOREIGN KEY (id_medicamento) REFERENCES medicamento(cod_medicamento);

ALTER TABLE dosis
    ADD CONSTRAINT dosis_receta_fk
    FOREIGN KEY (id_receta) REFERENCES receta(cod_receta);

/* Pagos */
CREATE TABLE pago (
    cod_boleta NUMBER(6) NOT NULL,
    id_receta NUMBER(7) NOT NULL,
    fecha_pago DATE NOT NULL,
    monto_total VARCHAR2(25) NOT NULL,
    metodo_pago VARCHAR2(25) NOT NULL,
    id_banco NUMBER(2)
);

ALTER TABLE pago
    ADD CONSTRAINT boleta_pk PRIMARY KEY (cod_boleta);

ALTER TABLE pago
    ADD CONSTRAINT pago_receta_fk
    FOREIGN KEY (id_receta) REFERENCES receta(cod_receta);

ALTER TABLE pago
    ADD CONSTRAINT pago_banco_fk
    FOREIGN KEY (id_banco) REFERENCES banco(cod_banco);

/* =========================================================
   CASO 2 - MODIFICACIONES MEDIANTE ALTER TABLE
   ========================================================= */

/* 1. Agregar precio unitario del medicamento.
      Rango permitido: $1.000 a $2.000.000 */
ALTER TABLE medicamento
    ADD (precio_unitario NUMBER(10));

ALTER TABLE medicamento
    ADD CONSTRAINT medicamento_precio_ck
    CHECK (precio_unitario BETWEEN 1000 AND 2000000);

/* 2. Restringir métodos de pago */
ALTER TABLE pago
    ADD CONSTRAINT pago_metodo_ck
    CHECK (metodo_pago IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA'));

/* 3. Eliminar edad y agregar fecha de nacimiento */
ALTER TABLE paciente
    DROP COLUMN edad;

ALTER TABLE paciente
    ADD (fecha_nacimiento DATE NOT NULL);
